"""Rebuild the original synthetic fixture; no market data is downloaded."""

import json
from pathlib import Path

import numpy as np
import pandas as pd

root = Path(__file__).resolve().parents[1] / "src/portfolio_sim/fixtures"
root.mkdir(exist_ok=True)
rng = np.random.default_rng(20261106)
log_returns = (0.12 - 0.5 * 0.25**2) / 252 + 0.25 / np.sqrt(252) * rng.standard_normal(756)
prices = np.r_[100.0, 100 * np.exp(np.cumsum(log_returns))]
assert len(prices) == 757 and np.isfinite(prices).all() and (prices > 0).all()
pd.DataFrame(
    {
        "date": pd.bdate_range("2022-01-03", periods=len(prices)).strftime("%Y-%m-%d"),
        "close": prices,
    }
).to_csv(root / "synthetic_daily.csv", index=False, float_format="%.10f")
provenance = {
    "kind": "synthetic_fixture",
    "source": (
        "Original illustrative data generated by scripts/generate_fixture.py; "
        "NOT WEGE3 or IBOV prices"
    ),
    "generated_on": "2026-11-06",
    "seed": 20261106,
    "generating_drift": 0.12,
    "generating_volatility": 0.25,
    "calendar": "757 weekdays from 2022-01-03; not an exchange trading calendar",
    "note": "Offline fixture exercises calibration only. It is not observed market history.",
}
(root / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
